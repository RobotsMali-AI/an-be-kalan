// Widget that rebuilds only when language changes
class LanguageAwareWidget extends StatelessWidget {
  final Widget Function(BuildContext context, String languageCode) builder;

  const LanguageAwareWidget({
    super.key,
    required this.builder,
  });

  @override
  Widget build(BuildContext context) {
    return Consumer<SimpleLocale>(
      builder: (context, locale, child) {
        return builder(context, locale.code);
      },
    );
  }
}

