String t(BuildContext context, String key) {
  final code = context.read<SimpleLocale>().code;
  // Try current language first, then fallback to Bambara, then return the key itself
  final translation = _strings[code]?[key] ?? _strings['bm']?[key] ?? key;
  return translation;
}

// Use this function only when you need the widget to rebuild when language changes
String tWatch(BuildContext context, String key) {
  final code = context.watch<SimpleLocale>().code;
  // Try current language first, then fallback to Bambara, then return the key itself
  final translation = _strings[code]?[key] ?? _strings['bm']?[key] ?? key;
  return translation;
}

// Static translation function that doesn't depend on context - use for static text
String tStatic(String key, String languageCode) {
  final translation =
      _strings[languageCode]?[key] ?? _strings['bm']?[key] ?? key;
  return translation;
}

// Efficient translation function that only rebuilds when language actually changes
String tEfficient(BuildContext context, String key) {
  final locale = context.read<SimpleLocale>();
  if (!locale.isInitialized) {
    return _strings['bm']?[key] ??
        key; // Fallback to Bambara if not initialized
  }
  final code = locale.code;
  final translation = _strings[code]?[key] ?? _strings['bm']?[key] ?? key;
  return translation;
}

